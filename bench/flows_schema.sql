-- Akvorado 2.x flows table (upstream schema, no data). Used only by bench.py component runs.
CREATE TABLE IF NOT EXISTS flows
(
    `TimeReceived` DateTime CODEC(DoubleDelta, LZ4),
    `SamplingRate` UInt64,
    `ExporterAddress` LowCardinality(IPv6),
    `ExporterName` LowCardinality(String),
    `ExporterGroup` LowCardinality(String),
    `ExporterRole` LowCardinality(String),
    `ExporterSite` LowCardinality(String),
    `ExporterRegion` LowCardinality(String),
    `ExporterTenant` LowCardinality(String),
    `SrcAddr` IPv6 CODEC(ZSTD(1)),
    `DstAddr` IPv6 CODEC(ZSTD(1)),
    `SrcNetMask` UInt8,
    `DstNetMask` UInt8,
    `SrcNetPrefix` String ALIAS multiIf(EType = 2048, concat(replaceRegexpOne(CAST((IPv6CIDRToRange(SrcAddr, CAST(96 + SrcNetMask, 'UInt8'))).1, 'String'), '^::ffff:', ''), '/', CAST(SrcNetMask, 'String')), EType = 34525, concat(CAST((IPv6CIDRToRange(SrcAddr, SrcNetMask)).1, 'String'), '/', CAST(SrcNetMask, 'String')), ''),
    `DstNetPrefix` String ALIAS multiIf(EType = 2048, concat(replaceRegexpOne(CAST((IPv6CIDRToRange(DstAddr, CAST(96 + DstNetMask, 'UInt8'))).1, 'String'), '^::ffff:', ''), '/', CAST(DstNetMask, 'String')), EType = 34525, concat(CAST((IPv6CIDRToRange(DstAddr, DstNetMask)).1, 'String'), '/', CAST(DstNetMask, 'String')), ''),
    `SrcAS` UInt32,
    `DstAS` UInt32,
    `SrcNetName` LowCardinality(String),
    `DstNetName` LowCardinality(String),
    `SrcNetRole` LowCardinality(String),
    `DstNetRole` LowCardinality(String),
    `SrcNetSite` LowCardinality(String),
    `DstNetSite` LowCardinality(String),
    `SrcNetRegion` LowCardinality(String),
    `DstNetRegion` LowCardinality(String),
    `SrcNetTenant` LowCardinality(String),
    `DstNetTenant` LowCardinality(String),
    `SrcCountry` FixedString(2),
    `DstCountry` FixedString(2),
    `SrcGeoCity` LowCardinality(String),
    `DstGeoCity` LowCardinality(String),
    `SrcGeoState` LowCardinality(String),
    `DstGeoState` LowCardinality(String),
    `DstASPath` Array(UInt32),
    `Dst1stAS` UInt32,
    `Dst2ndAS` UInt32,
    `Dst3rdAS` UInt32,
    `DstCommunities` Array(UInt32),
    `DstLargeCommunities` Array(UInt128),
    `InIfName` LowCardinality(String),
    `OutIfName` LowCardinality(String),
    `InIfDescription` LowCardinality(String),
    `OutIfDescription` LowCardinality(String),
    `InIfSpeed` UInt32,
    `OutIfSpeed` UInt32,
    `InIfConnectivity` LowCardinality(String),
    `OutIfConnectivity` LowCardinality(String),
    `InIfProvider` LowCardinality(String),
    `OutIfProvider` LowCardinality(String),
    `InIfBoundary` Enum8('undefined' = 0, 'external' = 1, 'internal' = 2),
    `OutIfBoundary` Enum8('undefined' = 0, 'external' = 1, 'internal' = 2),
    `EType` UInt32,
    `Proto` UInt32,
    `SrcPort` UInt16,
    `DstPort` UInt16,
    `Bytes` UInt64 CODEC(T64, LZ4),
    `Packets` UInt64 CODEC(T64, LZ4),
    `PacketSize` UInt64 ALIAS intDiv(Bytes, Packets),
    `PacketSizeBucket` LowCardinality(String) ALIAS multiIf(PacketSize < 64, '0-63', PacketSize < 128, '64-127', PacketSize < 256, '128-255', PacketSize < 512, '256-511', PacketSize < 768, '512-767', PacketSize < 1024, '768-1023', PacketSize < 1280, '1024-1279', PacketSize < 1501, '1280-1500', PacketSize < 2048, '1501-2047', PacketSize < 3072, '2048-3071', PacketSize < 4096, '3072-4095', PacketSize < 8192, '4096-8191', PacketSize < 10240, '8192-10239', PacketSize < 16384, '10240-16383', PacketSize < 32768, '16384-32767', PacketSize < 65536, '32768-65535', '65536-Inf'),
    `ForwardingStatus` UInt32,
    `FlowDirection` Enum8('undefined' = 0, 'ingress' = 1, 'egress' = 2),
    `TCPFlags` UInt16,
    INDEX idx_exportername ExporterName TYPE minmax GRANULARITY 4,
    INDEX idx_srcaddr SrcAddr TYPE bloom_filter(0.001) GRANULARITY 4,
    INDEX idx_dstaddr DstAddr TYPE bloom_filter(0.001) GRANULARITY 4,
    INDEX idx_srcas SrcAS TYPE bloom_filter(0.001) GRANULARITY 4,
    INDEX idx_dstas DstAS TYPE bloom_filter(0.001) GRANULARITY 4,
    INDEX idx_srcport SrcPort TYPE bloom_filter(0.001) GRANULARITY 4,
    INDEX idx_dstport DstPort TYPE bloom_filter(0.001) GRANULARITY 4,
    INDEX idx_srccountry SrcCountry TYPE bloom_filter(0.001) GRANULARITY 4,
    INDEX idx_dstcountry DstCountry TYPE bloom_filter(0.001) GRANULARITY 4,
    INDEX idx_inifprovider InIfProvider TYPE set(0) GRANULARITY 4,
    INDEX idx_outifprovider OutIfProvider TYPE set(0) GRANULARITY 4,
    INDEX idx_inifconnectivity InIfConnectivity TYPE set(0) GRANULARITY 4,
    INDEX idx_outifconnectivity OutIfConnectivity TYPE set(0) GRANULARITY 4,
    INDEX idx_inifboundary InIfBoundary TYPE set(0) GRANULARITY 4,
    INDEX idx_outifboundary OutIfBoundary TYPE set(0) GRANULARITY 4
)
ENGINE = MergeTree
PARTITION BY toYYYYMMDDhhmmss(toStartOfInterval(TimeReceived, toIntervalSecond(51840)))
PRIMARY KEY toStartOfFiveMinutes(TimeReceived)
ORDER BY (toStartOfFiveMinutes(TimeReceived), ExporterAddress, InIfName, OutIfName)
TTL TimeReceived + toIntervalSecond(2592000)
SETTINGS index_granularity = 8192, ttl_only_drop_parts = 1
